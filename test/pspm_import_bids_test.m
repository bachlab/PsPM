methods (Access = private)
    function compare_with_reference( ...
            testCase, actual_file, reference_file)

        actual = load(actual_file, 'data', 'infos');
        reference = load(reference_file, 'data', 'infos');

        testCase.assertTrue( ...
            isfield(actual, 'data') && isfield(actual, 'infos'), ...
            'The imported file does not contain data and infos.');

        testCase.assertTrue( ...
            isfield(reference, 'data') && ...
            isfield(reference, 'infos'), ...
            'The reference file does not contain data and infos.');

        testCase.verifyNumElements( ...
            actual.data, ...
            numel(reference.data), ...
            'The number of imported channels differs.');

        for channel_index = 1:numel(reference.data)
            actual_channel = actual.data{channel_index};
            reference_channel = reference.data{channel_index};

            testCase.compare_channel( ...
                actual_channel, ...
                reference_channel, ...
                channel_index);
        end

        testCase.compare_infos( ...
            actual.infos, ...
            reference.infos);
    end

    function compare_channel( ...
            testCase, actual_channel, reference_channel, channel_index)

        testCase.assertTrue( ...
            isfield(actual_channel, 'header') && ...
            isfield(actual_channel, 'data'), ...
            sprintf('Actual channel %d is incomplete.', ...
            channel_index));

        testCase.assertTrue( ...
            isfield(reference_channel, 'header') && ...
            isfield(reference_channel, 'data'), ...
            sprintf('Reference channel %d is incomplete.', ...
            channel_index));

        actual_type = string(actual_channel.header.chantype);
        reference_type = string(reference_channel.header.chantype);

        testCase.verifyEqual( ...
            actual_type, ...
            reference_type, ...
            sprintf('Channel type differs at position %d.', ...
            channel_index));

        testCase.verifyEqual( ...
            size(actual_channel.data), ...
            size(reference_channel.data), ...
            sprintf('Data size differs for channel "%s".', ...
            reference_type));

        testCase.verifyTrue( ...
            isequaln(actual_channel.data, reference_channel.data), ...
            sprintf('Data values differ for channel "%s".', ...
            reference_type));

        header_fields = { ...
            'chantype', ...
            'sr', ...
            'units', ...
            'StartTime' ...
        };

        for field_index = 1:numel(header_fields)
            field_name = header_fields{field_index};

            actual_has_field = ...
                isfield(actual_channel.header, field_name);

            reference_has_field = ...
                isfield(reference_channel.header, field_name);

            testCase.verifyEqual( ...
                actual_has_field, ...
                reference_has_field, ...
                sprintf( ...
                    'Header field "%s" differs for channel "%s".', ...
                    field_name, reference_type));

            if actual_has_field && reference_has_field
                testCase.verifyTrue( ...
                    isequaln( ...
                        actual_channel.header.(field_name), ...
                        reference_channel.header.(field_name)), ...
                    sprintf( ...
                        ['Header value "%s" differs for ' ...
                         'channel "%s".'], ...
                        field_name, reference_type));
            end
        end

        actual_has_markerinfo = ...
            isfield(actual_channel, 'markerinfo');

        reference_has_markerinfo = ...
            isfield(reference_channel, 'markerinfo');

        testCase.verifyEqual( ...
            actual_has_markerinfo, ...
            reference_has_markerinfo, ...
            sprintf( ...
                'markerinfo presence differs for channel "%s".', ...
                reference_type));

        if actual_has_markerinfo && reference_has_markerinfo
            testCase.verifyTrue( ...
                isequaln( ...
                    actual_channel.markerinfo, ...
                    reference_channel.markerinfo), ...
                sprintf( ...
                    'markerinfo differs for channel "%s".', ...
                    reference_type));
        end
    end

    function compare_infos(testCase, actual_infos, reference_infos)
        testCase.assertTrue( ...
            isfield(actual_infos, 'duration') && ...
            isfield(reference_infos, 'duration'), ...
            'infos.duration is missing.');

        testCase.verifyEqual( ...
            actual_infos.duration, ...
            reference_infos.duration, ...
            'AbsTol', ...
            1e-9, ...
            'infos.duration differs from the reference.');


        testCase.assertTrue( ...
            isfield(actual_infos, 'source') && ...
            isfield(actual_infos.source, 'file'), ...
            'Actual infos.source.file is missing.');

        testCase.assertTrue( ...
            isfield(reference_infos, 'source') && ...
            isfield(reference_infos.source, 'file'), ...
            'Reference infos.source.file is missing.');

        actual_sources = testCase.source_group_names( ...
            actual_infos.source.file, ...
            true);

        reference_sources = testCase.source_group_names( ...
            reference_infos.source.file, ...
            false);

        testCase.verifyEqual( ...
            actual_sources, ...
            reference_sources, ...
            ['The source-file groups or source filenames differ ' ...
             'from the reference.']);
    end

    function group_names = source_group_names( ...
            testCase, source_groups, require_existing_files)

        testCase.assertTrue( ...
            iscell(source_groups), ...
            'infos.source.file must be a cell array.');

        group_names = strings(numel(source_groups), 1);

        for group_index = 1:numel(source_groups)
            group = source_groups{group_index};

            testCase.assertTrue( ...
                iscell(group), ...
                sprintf( ...
                    'Source group %d must be a cell array.', ...
                    group_index));

            testCase.assertNumElements( ...
                group, ...
                2, ...
                sprintf( ...
                    ['Source group %d must contain exactly ' ...
                     'one JSON file and one TSV/TSV.GZ file.'], ...
                    group_index));

            paths = string(group(:));

            if require_existing_files
                testCase.verifyTrue( ...
                    all(isfile(paths)), ...
                    sprintf( ...
                        'Source group %d contains a missing file.', ...
                        group_index));
            end

            filenames = strings(numel(paths), 1);

            for file_index = 1:numel(paths)
                [~, name, extension] = fileparts(paths(file_index));
                filenames(file_index) = ...
                    string(name) + string(extension);
            end

            filenames = sort(filenames);
            group_names(group_index) = join(filenames, "|");
        end

        % Group order is not relevant, only group membership.
        group_names = sort(group_names);
    end

    function write_json(testCase, filepath, metadata)
        file_id = fopen(filepath, 'w');

        testCase.assertNotEqual( ...
            file_id, ...
            -1, ...
            sprintf('Could not open JSON file:\n%s', filepath));

        cleanup = onCleanup(@() fclose(file_id)); %#ok<NASGU>
        fwrite(file_id, jsonencode(metadata), 'char');
    end

    function types = channel_types(~, data)
        types = strings(numel(data), 1);

        for channel_index = 1:numel(data)
            types(channel_index) = string( ...
                data{channel_index}.header.chantype);
        end
    end

    function verify_gaze_source_files_present(testCase, infos)
        source_names = testCase.source_file_names(infos);

        eye_json = ...
            "sub-CalinetBonn01_task-acquisition_" + ...
            "recording-eye2_physio.json";

        eye_tsv = ...
            "sub-CalinetBonn01_task-acquisition_" + ...
            "recording-eye2_physio.tsv.gz";

        physioevents_json = ...
            "sub-CalinetBonn01_task-acquisition_" + ...
            "recording-eye2_physioevents.json";

        physioevents_tsv = ...
            "sub-CalinetBonn01_task-acquisition_" + ...
            "recording-eye2_physioevents.tsv.gz";

        expected_sources = [
            eye_json
            eye_tsv
            physioevents_json
            physioevents_tsv
        ];

        for source_index = 1:numel(expected_sources)
            testCase.verifyTrue( ...
                any(source_names == expected_sources(source_index)), ...
