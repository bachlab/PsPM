    function source_names = source_file_names(testCase, infos)
        testCase.assertTrue( ...
            isfield(infos, 'source') && ...
            isfield(infos.source, 'file'), ...
            'infos.source.file is missing.');

        source_groups = infos.source.file;

        testCase.assertTrue( ...
            iscell(source_groups), ...
            'infos.source.file must be a cell array.');

        source_names = strings(0, 1);

        for group_index = 1:numel(source_groups)
            group = source_groups{group_index};

            testCase.assertTrue( ...
                iscell(group), ...
                sprintf( ...
                    'Source group %d must be a cell array.', ...
                    group_index));

            paths = string(group(:));

            testCase.verifyTrue( ...
                all(isfile(paths)), ...
                sprintf( ...
                    'Source group %d contains a missing file.', ...
                    group_index));

            for file_index = 1:numel(paths)
                [~, name, extension] = fileparts(paths(file_index));
                source_names(end + 1, 1) = ...
                    string(name) + string(extension); %#ok<AGROW>
            end
        end
    end

