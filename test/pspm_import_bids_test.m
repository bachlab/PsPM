classdef pspm_import_bids_test < pspm_testcase
% Baseline and mutation tests for pspm_import_bids.
%
% Each test works on a fresh temporary copy of the BIDS dataset.
% The baseline test compares the complete import with a stored
% reference file. Mutation tests modify only the temporary copy
% and verify the expected importer behavior.
%
% The original dataset and reference file are never modified.

properties
    base_dataset
    reference_file

    temp_root
    work_dataset
    output_dir
end

methods (TestClassSetup)
    function locate_test_data(testCase)
        repo_root = fileparts(pspm_path);

        testCase.base_dataset = fullfile( ...
            repo_root, ...
            'ImportTestData', ...
            'BIDs', ...
            'Dataset');

        testCase.reference_file = fullfile( ...
            repo_root, ...
            'ImportTestData', ...
            'BIDs', ...
            'ref', ...
            'pspm_sub-CalinetBonn01_full.mat');

        testCase.assertTrue( ...
            isfolder(testCase.base_dataset), ...
            sprintf('BIDS test dataset not found:\n%s', ...
            testCase.base_dataset));

        testCase.assertTrue( ...
            isfile(testCase.reference_file), ...
            sprintf('BIDS reference file not found:\n%s', ...
            testCase.reference_file));
    end
end

methods (TestMethodSetup)
    function create_temporary_dataset(testCase)
        testCase.temp_root = tempname;
        mkdir(testCase.temp_root);

        testCase.work_dataset = fullfile( ...
            testCase.temp_root, ...
            'Dataset');

        [copy_status, copy_message] = copyfile( ...
            testCase.base_dataset, ...
            testCase.work_dataset);

        testCase.assertTrue(copy_status, copy_message);

        testCase.output_dir = fullfile( ...
            testCase.temp_root, ...
            'output');

        mkdir(testCase.output_dir);
    end
end

methods (TestMethodTeardown)
    function remove_temporary_dataset(testCase)
        if ~isempty(testCase.temp_root) && ...
                isfolder(testCase.temp_root)
            rmdir(testCase.temp_root, 's');
        end
    end
end

methods (Test)
    function test_baseline_matches_reference(testCase)
        [sts, outfiles] = pspm_import_bids( ...
            testCase.work_dataset, ...
            testCase.output_dir);

        testCase.verifyEqual( ...
            sts, ...
            1, ...
            'The baseline BIDS import failed.');

        testCase.assertNumElements( ...
            outfiles, ...
            1, ...
            'Expected exactly one imported PsPM file.');

        actual_file = outfiles{1};

        testCase.assertTrue( ...
            isfile(actual_file), ...
            sprintf('Imported PsPM file not found:\n%s', ...
            actual_file));

        testCase.compare_with_reference( ...
            actual_file, ...
            testCase.reference_file);
    end

    function test_missing_behavioral_events_is_optional(testCase)
        physio_dir = fullfile( ...
            testCase.work_dataset, ...
            'sub-CalinetBonn01', ...
            'physio');

        events_json = fullfile( ...
            physio_dir, ...
            'sub-CalinetBonn01_task-acquisition_events.json');

        events_tsv = fullfile( ...
            physio_dir, ...
            'sub-CalinetBonn01_task-acquisition_events.tsv');

        testCase.assertTrue(isfile(events_json));
        testCase.assertTrue(isfile(events_tsv));

        delete(events_json);
        delete(events_tsv);

        [sts, outfiles] = pspm_import_bids( ...
            testCase.work_dataset, ...
            testCase.output_dir);

        testCase.verifyEqual( ...
            sts, ...
            1, ...
            ['The importer should succeed when behavioral ' ...
             'events are missing.']);

        testCase.assertNumElements( ...
            outfiles, ...
            1, ...
            'Expected exactly one imported PsPM file.');

        output_file = outfiles{1};

        testCase.assertTrue( ...
            isfile(output_file), ...
            sprintf('Imported PsPM file not found:\n%s', ...
            output_file));

        imported = load(output_file, 'data', 'infos');

        actual_types = strings(numel(imported.data), 1);

        for channel_index = 1:numel(imported.data)
            actual_types(channel_index) = string( ...
                imported.data{channel_index}.header.chantype);
        end

        expected_types = [
            "ecg"
            "scr"
            "pupil_r"
            "gaze_x_r"
            "gaze_y_r"
            "blink_r"
            "saccade_r"
            "fixation_c"
        ];

        testCase.verifyEqual( ...
            sort(actual_types), ...
            sort(expected_types), ...
            ['Unexpected channel set after removing behavioral ' ...
             'events.']);

        testCase.verifyFalse( ...
            any(actual_types == "marker"), ...
            'A marker channel was imported without behavioral events.');

        testCase.verifyNumElements( ...
            imported.data, ...
            8, ...
            'Expected eight channels without the marker channel.');

        testCase.verify_behavioral_sources_absent( ...
            imported.infos);
    end

